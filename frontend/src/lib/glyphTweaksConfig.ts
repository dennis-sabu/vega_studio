export type TweakControlSpec =
  | {
      type: "slider";
      key: keyof AtmosphereTweaks;
      label: string;
      min: number;
      max: number;
      step: number;
      decimals: number;
      unit?: string;
      hint: string;
      disabled?: (t: AtmosphereTweaks) => boolean;
      hiddenFor?: SpeciesKey[];
    }
  | {
      type: "toggle";
      key: keyof AtmosphereTweaks;
      label: string;
      hint: string;
      hiddenFor?: SpeciesKey[];
    };

export interface TweakGroupSpec {
  id: string;
  title: string;
  controls: TweakControlSpec[];
}

